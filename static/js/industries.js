(function () {
  const DATA_URL = "/data/industries.json";
  const root = document.getElementById("industry-explorer");
  if (!root) return;

  const els = {
    q: root.querySelector("#ix-q"),
    category: root.querySelector("#ix-category"),
    maturity: root.querySelector("#ix-maturity"),
    cagr: root.querySelector("#ix-cagr"),
    coverage: root.querySelector("#ix-coverage"),
    count: root.querySelector("#ix-count"),
    tbody: root.querySelector("#ix-tbody"),
    pv: root.querySelector("#ix-pv"),
    rate: root.querySelector("#ix-rate"),
    years: root.querySelector("#ix-years"),
    result: root.querySelector("#ix-result"),
    yearList: root.querySelector("#ix-year-list"),
    warn: root.querySelector("#ix-warn"),
    loaded: root.querySelector("#ix-loaded"),
    details: root.querySelector("#ix-details"),
    dialog: root.querySelector("#ix-dialog"),
    title: root.querySelector("#ix-detail-title"),
    scenario: root.querySelector("#ix-scenario"),
    filters: root.querySelector(".ix-filters"),
    reset: root.querySelector("#ix-reset"),
    mobileSort: root.querySelector("#ix-sort-mobile"),
    mobileSortLabel: root.querySelector(".ix-mobile-sort"),
  };

  let items = [];
  let researchLinks = {};
  let selected = null;
  let sortKey = "rank";
  let sortDir = 1;

  const fmtMoney = (n) => {
    if (!Number.isFinite(n)) return "—";
    if (n >= 1000) return "$" + (n / 1000).toFixed(2) + "T";
    return "$" + n.toFixed(1) + "B";
  };

  const midpoint = (lo, hi) => {
    if (lo == null && hi == null) return null;
    if (lo == null) return Number(hi);
    if (hi == null) return Number(lo);
    return (Number(lo) + Number(hi)) / 2;
  };

  const cagrValue = (row) => {
    if (row.cagr_low == null || row.cagr_high == null) return null;
    return midpoint(row.cagr_low, row.cagr_high);
  };
  const cagrFilterValue = (row) => cagrValue(row) ?? (row.cagr_low == null ? null : Number(row.cagr_low));
  const marketValue = (row) => midpoint(row.market_low, row.market_high);

  function escapeHtml(value) {
    return String(value == null ? "" : value)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

  function safeSourceLink(url, label) {
    if (!url) return "";
    try {
      const parsed = new URL(url);
      if (parsed.protocol !== "https:") return "";
      return '<a href="' + escapeHtml(parsed.href) + '">' + escapeHtml(label) + "</a>";
    } catch (_) {
      return "";
    }
  }

  function appendixLink(url) {
    if (typeof url !== "string" || !/^\/post\/50-high-potential-industries\/#evidence-[a-z-]+$/.test(url)) return "";
    return '<a href="' + escapeHtml(url) + '">Read claim-level evidence appendix</a>';
  }

  function evidenceLabel(row) {
    if (row.estimate_verification_status === "corrected") return "Sourced estimate · " + row.market_year;
    const baseline = row.sourced_baseline;
    if (!baseline) return "Unverified estimates";
    const kind = row.verification_status === "context" ? "Sourced context" : "Sourced baseline";
    return kind + " · " + baseline.year;
  }

  function baselineDetails(row) {
    const baseline = row.sourced_baseline;
    if (!baseline) return "";
    const source = baseline.source || {};
    const unit = String(baseline.unit || "");
    const currency = String(baseline.currency || "");
    const value = [currency && !unit.includes(currency) ? currency : "", baseline.value, unit].filter((part) => part !== "").join(" ");
    return '<section class="ix-details" aria-label="Separately sourced evidence"><h4>' + escapeHtml(evidenceLabel(row)) + "</h4>" +
      "<dl><dt>Measure</dt><dd>" + escapeHtml(baseline.metric) +
      "</dd><dt>Value and period</dt><dd>" + escapeHtml(value + " · " + baseline.year) +
      "</dd><dt>Geography</dt><dd>" + escapeHtml(baseline.geography) +
      "</dd><dt>Market definition</dt><dd>" + escapeHtml(baseline.market_definition) +
      "</dd><dt>Source</dt><dd>" + (safeSourceLink(source.url, source.publisher + " — " + source.title) || "Source unavailable") +
      " · " + escapeHtml(source.published) + "</dd></dl><p class=\"ix-note\">" +
      escapeHtml(baseline.relationship_to_estimate || "This separate measure does not verify the original estimates or forecasts.") + "</p></section>";
  }

  function relatedResearch(row) {
    const links = researchLinks[String(row.rank)];
    if (!Array.isArray(links)) return "";
    const markup = links.map((link) => {
      // These routes are generated by Hugo; reject unexpected external or executable URLs.
      if (typeof link.url !== "string" || !link.url.startsWith("/") || link.url.startsWith("//") || /[\\\s]/.test(link.url)) return "";
      return '<a class="ix-btn" href="' + escapeHtml(link.url) + '">' + escapeHtml(link.label) + "</a>";
    }).filter(Boolean).join("");
    if (!markup) return "";
    const label = ' aria-label="Related research for ' + escapeHtml(row.name) + '"';
    return "<nav" + label + '><h4>Continue the research</h4><div class="ix-actions">' + markup + "</div></nav>";
  }

  function updateSortState() {
    root.querySelectorAll("th[data-sort]").forEach((header) => {
      const active = header.getAttribute("data-sort") === sortKey;
      header.setAttribute(
        "aria-sort",
        active ? (sortDir === 1 ? "ascending" : "descending") : "none"
      );
    });
  }

  function compareRows(a, b) {
    let av = sortKey === "cagr" ? cagrFilterValue(a) : a[sortKey];
    let bv = sortKey === "cagr" ? cagrFilterValue(b) : b[sortKey];

    if (av == null && bv == null) return 0;
    if (av == null) return 1;
    if (bv == null) return -1;
    if (typeof av === "string") return av.localeCompare(bv) * sortDir;
    return (Number(av) - Number(bv)) * sortDir;
  }

  function applyFilters() {
    if (!items.length) return;
    const q = (els.q.value || "").trim().toLowerCase();
    const cat = els.category.value;
    const mat = els.maturity.value;
    const cagrMin = els.cagr.value ? Number(els.cagr.value) : null;

    const rows = items
      .filter((row) => {
        if (cat && row.category !== cat) return false;
        if (mat && row.maturity !== mat) return false;
        if (cagrMin != null) {
          const cagr = cagrFilterValue(row);
          if (cagr == null || cagr < cagrMin) return false;
        }
        if (q) {
          const searchable = [row.name, row.tech, row.notes, row.category, row.maturity]
            .join(" ")
            .toLowerCase();
          if (!searchable.includes(q)) return false;
        }
        return true;
      })
      .sort(compareRows);

    els.count.textContent = "Showing " + rows.length + " of " + items.length;
    updateSortState();
    if (els.mobileSort) els.mobileSort.value = sortKey;
    renderTable(rows);
  }

  function renderTable(rows) {
    if (!rows.length) {
      els.tbody.innerHTML = '<tr><td colspan="5" class="ix-empty">No matching industries. Try another search or clear the filters.</td></tr>';
      return;
    }

    els.tbody.innerHTML = rows
      .map((row) => {
        const isSelected = selected && selected.rank === row.rank;
        return (
          '<tr id="ix-industry-' + row.rank + '" data-rank="' +
          row.rank +
          '" class="' +
          (isSelected ? "is-selected" : "") +
          '">' +
          '<td class="ix-rank">' +
          row.rank +
          "</td>" +
          '<td class="ix-industry-cell"><button type="button" class="ix-select" data-rank="' + row.rank +
          '" aria-label="' + escapeHtml("View details for " + row.name) +
          '" aria-haspopup="dialog" aria-controls="ix-dialog"><span class="ix-industry-name">' +
          escapeHtml(row.name) + '</span><span class="ix-open-label">View details <span aria-hidden="true">→</span></span></button><span class="ix-chip">' + escapeHtml(row.category) + '</span><small class="ix-evidence">' + escapeHtml(evidenceLabel(row)) +
          (row.sourced_baseline ? "<br>Original estimates unverified" : "") +
          (row.estimate_note ? "<br>" + escapeHtml(row.estimate_note) : "") + "</small></td>" +
          '<td class="ix-tech" data-label="Key technologies">' +
          escapeHtml(row.tech) +
          "</td>" +
          '<td data-label="Market size · see year">' +
          escapeHtml(row.market_label) +
          "</td>" +
          '<td data-label="Growth · CAGR">' +
          escapeHtml(row.cagr_label) +
          "</td>" +
          "</tr>"
        );
      })
      .join("");
  }

  function clearScenario(message) {
    els.pv.value = "";
    els.rate.value = "";
    els.result.textContent = "Enter values to calculate";
    els.yearList.innerHTML = "";
    els.warn.textContent = message || "";
  }

  function selectRank(rank) {
    selected = items.find((item) => item.rank === rank) || null;
    applyFilters();
    if (!selected) return;
    const pv = marketValue(selected);
    const rate = cagrValue(selected);
    if (els.title) els.title.textContent = selected.name;
    if (els.scenario) els.scenario.open = false;
    els.years.value = selected.estimate_verification_status === "corrected" ? String(selected.cagr_end_year - selected.cagr_start_year) : "5";
    els.loaded.textContent = "Selected: " + selected.name;
    els.details.innerHTML =
      '<p class="ix-detail-intro">' + escapeHtml(selected.tech) + "</p>" + relatedResearch(selected) +
      '<section aria-label="Screening estimates"><h3>Screening estimates</h3><p class="ix-note">' + escapeHtml(selected.estimate_note || "Original figures are unverified research leads.") + '</p>' +
      (selected.evidence_appendix_url ? '<p>' + appendixLink(selected.evidence_appendix_url) + "</p>" : "") +
      "<dl><dt>Category</dt><dd>" + escapeHtml(selected.category) +
      "</dd><dt>Maturity</dt><dd>" + escapeHtml(selected.maturity) +
      " (editorial)</dd><dt>Market size · see year</dt><dd>" + escapeHtml(selected.market_label) +
      "</dd><dt>Growth · CAGR</dt><dd>" + escapeHtml(selected.cagr_label) +
      "</dd><dt>Projected size</dt><dd>" + escapeHtml(selected.projected_label) +
      "</dd><dt>Notes</dt><dd>" + escapeHtml(selected.notes) +
      "</dd><dt>Market definition</dt><dd>" + escapeHtml(selected.market_definition || "Not recorded") +
      "</dd><dt>Geography</dt><dd>" + escapeHtml(selected.geography || "Not recorded") +
      (selected.market_year ? "</dd><dt>Data year</dt><dd>" + escapeHtml(selected.market_year) : "") +
      (selected.cagr_start_year ? "</dd><dt>CAGR period</dt><dd>" + escapeHtml(selected.cagr_start_year + "–" + selected.cagr_end_year) : "") +
      (selected.forecast_status ? "</dd><dt>Estimate / forecast status</dt><dd>" + escapeHtml(selected.forecast_status) : "") +
      "</dd><dt>Numeric source and publication date</dt><dd>" +
      (safeSourceLink(selected.numeric_source_url, "Open numeric source") || "No numeric source recorded") +
      "; " + escapeHtml(selected.source_date || "date not recorded") +
      "</dd><dt>Related primary material</dt><dd>" +
      (safeSourceLink(selected.context_url, "Read category context (does not verify figures)") || "None linked") +
      "</dd></dl></section>" + baselineDetails(selected);
    if (els.dialog && !els.dialog.open) els.dialog.showModal();
    if (els.dialog) els.dialog.scrollTop = 0;

    if (pv == null || rate == null) {
      clearScenario(
        "This row lacks a usable market value or a two-sided CAGR range. Previous values were cleared; enter your own assumptions to run a scenario."
      );
      return;
    }

    els.warn.textContent = "";
    els.pv.value = String(Math.round(pv * 10) / 10);
    els.rate.value = String(Math.round(rate * 10) / 10);
    els.loaded.textContent = selected.estimate_verification_status === "corrected"
      ? "Loaded the sourced " + selected.market_year + " baseline for " + selected.name + ". The midpoint growth rate is a calculator assumption, not a publisher point forecast; the source scenario covers " + selected.cagr_start_year + "–" + selected.cagr_end_year + "."
      : "Loaded indicative, unverified values for " + selected.name + ". Check definitions and sources before use.";
    calculate();
  }

  function calculate() {
    const pvRaw = els.pv.value.trim();
    const rateRaw = els.rate.value.trim();
    const yearsRaw = els.years.value.trim();
    const pv = Number(pvRaw);
    const ratePercent = Number(rateRaw);
    const years = Number(yearsRaw);

    const valid =
      pvRaw !== "" &&
      rateRaw !== "" &&
      yearsRaw !== "" &&
      Number.isFinite(pv) &&
      pv >= 0 &&
      Number.isFinite(ratePercent) &&
      ratePercent > -100 &&
      Number.isInteger(years) &&
      years >= 1 &&
      years <= 50;

    if (!valid) {
      els.result.textContent = "Enter valid values to calculate";
      els.yearList.innerHTML = "";
      return;
    }

    const rate = ratePercent / 100;
    const fv = pv * Math.pow(1 + rate, years);
    els.result.textContent =
      "≈ " + fmtMoney(fv) + " after " + years + (years === 1 ? " year" : " years");

    let html = "";
    for (let year = 1; year <= years; year += 1) {
      html += "<li>Year " + year + ": " + fmtMoney(pv * Math.pow(1 + rate, year)) + "</li>";
    }
    els.yearList.innerHTML = html;
  }

  root.addEventListener("input", (event) => {
    if (["ix-q", "ix-category", "ix-maturity", "ix-cagr"].includes(event.target.id)) {
      applyFilters();
    }
    if (["ix-pv", "ix-rate", "ix-years"].includes(event.target.id)) {
      els.warn.textContent = "";
      calculate();
    }
  });

  root.addEventListener("change", (event) => {
    if (["ix-category", "ix-maturity", "ix-cagr"].includes(event.target.id)) applyFilters();
    if (event.target.id === "ix-sort-mobile") {
      sortKey = els.mobileSort.value;
      sortDir = 1;
      applyFilters();
    }
  });

  root.addEventListener("click", (event) => {
    if (event.target.closest("#ix-reset")) {
      for (const input of [els.q, els.category, els.maturity, els.cagr]) input.value = "";
      sortKey = "rank";
      sortDir = 1;
      applyFilters();
      els.q.focus?.();
      return;
    }
    const sortButton = event.target.closest(".ix-sort[data-sort]");
    if (sortButton) {
      const key = sortButton.getAttribute("data-sort");
      if (sortKey === key) sortDir *= -1;
      else {
        sortKey = key;
        sortDir = 1;
      }
      applyFilters();
      return;
    }

    const button = event.target.closest(".ix-select[data-rank]");
    if (button) selectRank(Number(button.getAttribute("data-rank")));
  });

  if (els.dialog) {
    els.dialog.addEventListener("close", () => {
      const button = Array.from(els.tbody.querySelectorAll(".ix-select"))
        .find((entry) => Number(entry.dataset.rank) === selected?.rank);
      (button || els.q).focus({ preventScroll: true });
    });
    els.dialog.addEventListener("click", (event) => {
      if (event.target !== els.dialog) return;
      const bounds = els.dialog.getBoundingClientRect();
      if (event.clientX < bounds.left || event.clientX > bounds.right || event.clientY < bounds.top || event.clientY > bounds.bottom) els.dialog.close();
    });
  }
  // A source-review link must reveal its destination even when it is a closed disclosure.
  const revealSourceNotes = () => {
    if (window.location.hash === "#source-review-notes") {
      const notes = root.querySelector("#source-review-notes");
      if (notes) { notes.open = true; notes.scrollIntoView(); }
    }
  };
  if (typeof window !== "undefined" && window.addEventListener) {
    window.addEventListener("hashchange", revealSourceNotes);
    revealSourceNotes();
  }

  function loadData(payload) {
    if (!payload || !Array.isArray(payload.industries) || !payload.industries.length) {
      throw new Error("Invalid industry data");
    }
    items = payload.industries;
    const linkData = root.querySelector("#ix-research-links");
    if (linkData) {
      try { researchLinks = JSON.parse(linkData.textContent) || {}; }
      catch (_) { researchLinks = {}; }
    }
    const cagrCount = items.filter((item) => cagrFilterValue(item) != null).length;
    const calculatorCount = items.filter(
      (item) => marketValue(item) != null && cagrValue(item) != null
    ).length;
    els.coverage.textContent =
      "Data coverage: numeric CAGR or lower bound for " +
      cagrCount +
      "/" +
      items.length +
      "; rows with market and two-sided CAGR values for " +
      calculatorCount +
      "/" +
      items.length +
      ". The battery-cell row has a sourced 2022 correction; other original estimates remain unverified; " + items.filter((row) => row.sourced_baseline && row.verification_status !== "context").length +
      " rows have a separate sourced baseline and " + items.filter((row) => row.sourced_baseline && row.verification_status === "context").length + " have sourced broader-market context.";
    applyFilters();
    for (const element of [els.filters, els.reset, els.mobileSortLabel]) {
      if (element) element.hidden = false;
    }
    calculate();
    if (typeof window !== "undefined" && window.location) {
      const rank = Number(new URL(window.location.href).searchParams.get("industry"));
      if (Number.isInteger(rank) && items.some((row) => row.rank === rank)) selectRank(rank);
    }
  }

  try {
    const embedded = root.querySelector("#ix-dataset");
    if (!embedded) throw new Error("Embedded industry data missing");
    loadData(JSON.parse(embedded.textContent));
  } catch (error) {
    fetch(DATA_URL)
      .then((response) => {
        if (!response.ok) throw new Error("Industry data request failed");
        return response.json();
      })
      .then(loadData)
      .catch(() => {
        els.count.textContent = "The full industry list remains available below.";
        els.coverage.textContent = "Interactive data is temporarily unavailable.";
        els.warn.textContent = "Refresh the page or download the CSV to inspect the data.";
      });
  }
})();
